from typing import List, Optional
from pydantic import BaseModel, Field, model_validator


class BuyerPrepareRequest(BaseModel):
    """
    Request model to prepare an autonomous negotiation plan for the Buyer Agent.
    """
    product_id: str = Field(..., description="Unique product identifier", examples=["prod-1"])
    product_name: str = Field(..., description="Display title of the product", examples=["Aura Horizon Chrono Pro"])
    merchant: str = Field(..., description="Merchant or store name", examples=["Chronos Official"])
    advertised_price: float = Field(..., gt=0, description="Current advertised list price", examples=[299.0])
    target_price: float = Field(..., gt=0, description="Customer target price", examples=[240.0])
    max_price: Optional[float] = Field(None, gt=0, description="Maximum ceiling price customer will accept", examples=[270.0])
    delivery_preference: Optional[str] = Field("Free standard delivery", description="Delivery preference", examples=["Free standard delivery"])
    requirements: Optional[List[str]] = Field(default_factory=list, description="Additional customer constraints or preferences")

    @model_validator(mode="after")
    def validate_pricing_bounds(self) -> "BuyerPrepareRequest":
        if self.target_price > self.advertised_price:
            raise ValueError(f"Target price (${self.target_price}) cannot exceed the advertised price (${self.advertised_price}).")
        
        if self.max_price is None:
            # If maximum price is not explicitly set, default to advertised price as upper ceiling
            self.max_price = self.advertised_price
        elif self.max_price < self.target_price:
            raise ValueError(f"Maximum acceptable price (${self.max_price}) cannot be less than target price (${self.target_price}).")
        
        return self


class BuyerPrepareResponse(BaseModel):
    """
    Structured negotiation plan generated by the NEGOZA Buyer Agent.
    """
    status: str = Field(default="success", description="Status indicator")
    agent: str = Field(default="buyer", description="Agent role identifier")
    product_id: str = Field(..., description="Product ID being negotiated")
    product_name: str = Field(..., description="Product name")
    merchant: str = Field(..., description="Merchant name")
    advertised_price: float = Field(..., description="Original advertised price")
    target_price: float = Field(..., description="Customer target price")
    max_price: float = Field(..., description="Customer maximum ceiling price")
    opening_offer: float = Field(..., description="Initial opening offer calculated for negotiation")
    strategy: str = Field(..., description="Strategic negotiation methodology")
    reasoning: str = Field(..., description="Economic and situational justification for the offer")
    delivery_conditions: str = Field(..., description="Delivery terms to be negotiated")
    rejection_conditions: List[str] = Field(default_factory=list, description="Strict conditions under which an offer must be declined")
    product_summary: str = Field(..., description="Brief summary of the item from buyer perspective")
    customer_objective: str = Field(..., description="Core purchasing mission for this negotiation")
    model: Optional[str] = Field(None, description="Gemini model that drafted the plan")
