import asyncio
import logging
import os
from pathlib import Path
from typing import Optional, Dict, Any
from dotenv import load_dotenv
from google import genai
from google.genai import errors

logger = logging.getLogger(__name__)

# Ensure backend/.env is loaded
BASE_DIR = Path(__file__).resolve().parent.parent.parent
env_path = BASE_DIR / ".env"
if env_path.exists():
    load_dotenv(dotenv_path=env_path, override=True)


class GeminiService:
    """
    Reusable service for interacting with Google Gemini models using
    the official google-genai SDK.
    """

    def __init__(self, api_key: Optional[str] = None, default_model: Optional[str] = None):
        self.api_key = api_key or os.getenv("GEMINI_API_KEY")
        self.default_model = default_model or os.getenv("GEMINI_MODEL", "gemini-3.5-flash")
        self.per_call_timeout = float(os.getenv("GEMINI_PER_CALL_TIMEOUT", "18.0"))
        self.max_retries = int(os.getenv("GEMINI_MAX_RETRIES", "1"))
        self._client: Optional[genai.Client] = None
        self._loop: Optional[asyncio.AbstractEventLoop] = None

    def _get_client(self) -> genai.Client:
        """
        Lazily initialize and return the official google-genai Client.
        Validates that GEMINI_API_KEY is present and not a placeholder.
        Re-initializes if the running asyncio event loop has changed.
        """
        current_key = os.getenv("GEMINI_API_KEY") or self.api_key
        if not current_key or current_key.strip() in ("", "your_gemini_api_key_here"):
            raise ValueError("GEMINI_API_KEY is not configured. Please set your Gemini API key in backend/.env")

        clean_key = current_key.strip()

        try:
            running_loop = asyncio.get_running_loop()
        except RuntimeError:
            running_loop = None

        if self._client is None or self.api_key != clean_key or self._loop != running_loop:
            self.api_key = clean_key
            self._client = genai.Client(api_key=self.api_key)
            self._loop = running_loop

        return self._client

    async def generate_response(
        self,
        message: str,
        model: Optional[str] = None,
        system_instruction: Optional[str] = None,
        response_mime_type: Optional[str] = None,
    ) -> str:
        """
        Asynchronously generates text from the Gemini API using the non-blocking
        client.aio interface.

        :param message: The user message or prompt.
        :param model: Optional override for the model identifier.
        :param system_instruction: Optional system instruction for agent persona/guidance.
        :param response_mime_type: Optional MIME type (e.g. 'application/json').
        :return: Generated text response from Gemini.
        """
        if not message or not message.strip():
            raise ValueError("Message cannot be empty.")

        target_model = model or self.default_model
        client = self._get_client()

        config_dict: Dict[str, Any] = {}
        if system_instruction:
            config_dict["system_instruction"] = system_instruction
        if response_mime_type:
            config_dict["response_mime_type"] = response_mime_type

        max_retries = self.max_retries
        for attempt in range(max_retries + 1):
            try:
                # Enforce per-call timeout so slow or hung Gemini requests do not stall the backend
                response = await asyncio.wait_for(
                    client.aio.models.generate_content(
                        model=target_model,
                        contents=message.strip(),
                        config=config_dict if config_dict else None,
                    ),
                    timeout=self.per_call_timeout
                )

                if not response or not hasattr(response, "text") or response.text is None:
                    return "No text generated by Gemini."

                return response.text

            except (asyncio.TimeoutError, TimeoutError) as timeout_err:
                logger.warning(
                    f"Gemini API request timed out after {self.per_call_timeout}s "
                    f"(attempt {attempt + 1}/{max_retries + 1})."
                )
                if attempt < max_retries:
                    await asyncio.sleep(1.0)
                    continue
                raise TimeoutError(
                    f"Gemini API call timed out after {self.per_call_timeout} seconds."
                ) from timeout_err

            except errors.APIError as err:
                err_message = str(err)
                is_transient = (
                    getattr(err, "code", None) == 503
                    or "503" in err_message
                    or "UNAVAILABLE" in err_message
                    or "high demand" in err_message.lower()
                )
                if is_transient and attempt < max_retries:
                    logger.warning(
                        f"Gemini transient 503 error on attempt {attempt + 1}: {err_message}. Retrying in 1.5s..."
                    )
                    await asyncio.sleep(1.5)
                    continue

                # Detect invalid / unauthorized API keys
                if (
                    "API_KEY_INVALID" in err_message
                    or "API key not valid" in err_message
                    or getattr(err, "code", None) == 400
                    and "API key" in err_message
                ):
                    raise PermissionError("Invalid Gemini API key. Please check that GEMINI_API_KEY in backend/.env is valid.") from err

                # If the primary model failed due to 503 (high demand) or 429 (quota), try alternative models before giving up
                is_capacity_issue = is_transient or getattr(err, "code", None) == 429 or "RESOURCE_EXHAUSTED" in err_message
                if is_capacity_issue:
                    fallback_pool = ["gemini-3.5-flash", "gemini-3.6-flash", "gemini-3.5-flash-lite"]
                    alternatives = [m for m in fallback_pool if m != target_model]
                    logger.warning(f"Primary model '{target_model}' encountered capacity issue ({err_message}). Trying alternatives: {alternatives}")

                    for alt_model in alternatives:
                        try:
                            logger.info(f"Attempting failover to alternative model '{alt_model}'...")
                            fallback_resp = await asyncio.wait_for(
                                client.aio.models.generate_content(
                                    model=alt_model,
                                    contents=message.strip(),
                                    config=config_dict if config_dict else None,
                                ),
                                timeout=self.per_call_timeout
                            )
                            if fallback_resp and hasattr(fallback_resp, "text") and fallback_resp.text:
                                logger.info(f"Failover to '{alt_model}' succeeded!")
                                return fallback_resp.text
                        except Exception as fb_err:
                            logger.warning(f"Failover to '{alt_model}' failed: {fb_err}")
                            continue

                # Handle quota / resource limits with clear message
                if getattr(err, "code", None) == 429 or "RESOURCE_EXHAUSTED" in err_message:
                    raise RuntimeError("Gemini API quota exceeded. Please try again later.") from err

                # General upstream API error
                raise RuntimeError(f"Gemini API error ({getattr(err, 'code', 'upstream')}): {getattr(err, 'message', err_message)}") from err


# Shared singleton instance
gemini_service = GeminiService()
